"""Check a commit message against Ajimu's neutral authorship conventions.

Rejects: an empty subject, a subject over 90 characters, a subject ending with a
period, and any reference to AI, assistants, LLMs, code-generation products or
vendors, "generated by" or co-author trailers. Warns when the subject exceeds 72
characters or does not look imperative ("Added", "Fixes", "Updating" ...).
Ordinary product words such as "models" or "providers" are allowed.

Usage:
    python check_commit_message.py MESSAGE_FILE
    python check_commit_message.py --message "Subject line"

As a git hook, save this file somewhere stable and create .git/hooks/commit-msg:
    #!/bin/sh
    exec python /path/to/check_commit_message.py "$1"

Exit status: 0 = acceptable (warnings may be printed), 1 = rejected, 2 = usage error.
"""
import argparse
import re
import sys
from pathlib import Path

FORBIDDEN = re.compile(
    r'\b(?:ai|a\.i\.|llms?|assistants?|chatbots?|gpt[\w.-]*|copilot|chatgpt|openai|anthropic|claude|codex|gemini)\b'
    r'|artificial[ -]intelligence|co-authored-by|generated[ -]by|generated with|written by an?\b',
    re.IGNORECASE)
NOT_IMPERATIVE = re.compile(r'^(?:added|adds|adding|fixed|fixes|fixing|updated|updates|updating|changed|changes|'
                            r'removed|removes|implemented|implements|refactored|refactors|created|creates)\b',
                            re.IGNORECASE)


def check(text):
    """Return (errors, warnings) for one commit message, ignoring git comment lines."""
    lines = [line for line in text.splitlines() if not line.startswith('#')]
    while lines and not lines[0].strip():
        lines.pop(0)
    errors, warnings = [], []
    subject = lines[0].strip() if lines else ''
    if not subject:
        return ['the subject line is empty'], warnings
    if len(subject) > 90:
        errors.append(f'the subject has {len(subject)} characters; keep it at most 72 (90 is the hard limit)')
    elif len(subject) > 72:
        warnings.append(f'the subject has {len(subject)} characters; 72 or fewer reads best')
    if subject.endswith('.'):
        errors.append('do not end the subject with a period')
    if NOT_IMPERATIVE.match(subject):
        warnings.append('write the subject in the imperative mood, for example "Add", "Fix", "Preserve"')
    if len(lines) > 1 and lines[1].strip():
        warnings.append('leave a blank line between the subject and the body')
    for number, line in enumerate(lines, 1):
        match = FORBIDDEN.search(line)
        if match:
            errors.append(f'line {number}: remove the authorship or tool reference "{match.group(0)}"')
    return errors, warnings


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('file', nargs='?', help='commit message file, such as .git/COMMIT_EDITMSG')
    parser.add_argument('--message', help='check this text instead of a file')
    args = parser.parse_args(argv)
    if bool(args.file) == bool(args.message):
        parser.print_usage(sys.stderr)
        return 2
    try:
        text = args.message if args.message else Path(args.file).read_text(encoding='utf-8')
    except OSError as error:
        print(f'error: {error}', file=sys.stderr)
        return 2
    errors, warnings = check(text)
    for warning in warnings:
        print(f'warning: {warning}')
    for error in errors:
        print(f'error: {error}')
    if errors:
        print('commit message rejected')
        return 1
    print('commit message ok')
    return 0


if __name__ == '__main__':
    sys.exit(main())
